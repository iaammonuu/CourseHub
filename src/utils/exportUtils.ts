import { jsPDF } from 'jspdf';

export interface EnrollmentReceiptData {
  enrollmentId: string;
  studentName: string;
  studentId: string;
  studentEmail?: string;
  studentDepartment?: string;
  courseCode: string;
  courseTitle: string;
  facultyName: string;
  semester: string;
  schedule?: string;
  room?: string;
  credits?: number;
  enrolledAt: string;
  universityName?: string;
}

/**
 * Generates and downloads a university PDF Enrollment Confirmation Receipt using jsPDF
 */
export function downloadEnrollmentReceiptPdf(data: EnrollmentReceiptData): void {
  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });
  const uniName = data.universityName || 'Westbridge Institute of Technology';
  const generatedDate = new Date().toLocaleString('en-US', {
    dateStyle: 'medium',
    timeStyle: 'short',
  });

  // Top Header Banner
  doc.setFillColor(30, 41, 59); // #1E293B
  doc.rect(0, 0, 210, 36, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(18);
  doc.text('CourseHub Academic Registrar', 16, 16);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.text(`${uniName} · Official Course Enrollment Receipt`, 16, 24);
  doc.text(`Receipt ID: ${data.enrollmentId}`, 194, 16, { align: 'right' });
  doc.text(`Issued: ${generatedDate}`, 194, 24, { align: 'right' });

  // Status Confirmation Box
  doc.setFillColor(240, 253, 244);
  doc.setDrawColor(22, 163, 74);
  doc.roundedRect(16, 44, 178, 16, 2, 2, 'FD');
  doc.setTextColor(21, 128, 61);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.text(
    'ENROLLMENT CONFIRMED — ACTIVE SEAT RESERVED',
    22,
    54
  );

  // Student Information Section
  doc.setTextColor(15, 23, 42);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.text('1. Student Information', 16, 72);
  doc.setDrawColor(226, 232, 240);
  doc.line(16, 75, 194, 75);

  const studentRows: Array<[string, string]> = [
    ['Student Full Name', data.studentName],
    ['Student ID', data.studentId],
    ['University Email', data.studentEmail || 'N/A'],
    ['Academic Department', data.studentDepartment || 'General Studies'],
  ];

  let y = 83;
  studentRows.forEach(([label, val]) => {
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(10);
    doc.setTextColor(100, 116, 139);
    doc.text(label, 20, y);

    doc.setFont('helvetica', 'bold');
    doc.setTextColor(15, 23, 42);
    doc.text(String(val), 85, y);
    y += 8;
  });

  // Course Registration Details Section
  y += 6;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.setTextColor(15, 23, 42);
  doc.text('2. Registered Course Details', 16, y);
  doc.line(16, y + 3, 194, y + 3);
  y += 11;

  const enrolledFormatted = new Date(data.enrolledAt).toLocaleString('en-US', {
    dateStyle: 'medium',
    timeStyle: 'short',
  });

  const courseRows: Array<[string, string]> = [
    ['Course Code', data.courseCode],
    ['Course Name', data.courseTitle],
    ['Assigned Faculty', data.facultyName],
    ['Academic Semester', data.semester],
    ['Class Schedule', data.schedule || 'TBA'],
    ['Lecture Room', data.room || 'TBA'],
    ['Credit Hours', `${data.credits || 4} Credits`],
    ['Enrollment Timestamp', enrolledFormatted],
  ];

  courseRows.forEach(([label, val]) => {
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(10);
    doc.setTextColor(100, 116, 139);
    doc.text(label, 20, y);

    doc.setFont('helvetica', 'bold');
    doc.setTextColor(15, 23, 42);
    doc.text(String(val), 85, y);
    y += 8.5;
  });

  // Footer Verification Note
  doc.setDrawColor(203, 213, 225);
  doc.line(16, 255, 194, 255);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(100, 116, 139);
  doc.text(
    'This document is an official digital enrollment confirmation generated by CourseHub.',
    16,
    262
  );
  doc.text(
    `Verification Hash: CH-${data.enrollmentId}-${data.studentId}-${data.courseCode}`,
    16,
    268
  );

  doc.save(`CourseHub_Receipt_${data.studentId}_${data.courseCode}.pdf`);
}

/**
 * Generates a complete semester schedule PDF for all active enrollments of a student
 */
export function downloadFullSchedulePdf(
  student: { userId: string; name: string; email: string; department: string },
  enrollments: EnrollmentReceiptData[]
): void {
  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });
  const generatedDate = new Date().toLocaleString('en-US', {
    dateStyle: 'medium',
    timeStyle: 'short',
  });

  doc.setFillColor(37, 99, 235); // #2563EB
  doc.rect(0, 0, 210, 32, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.text('CourseHub — Official Student Schedule Confirmation', 16, 15);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.text(
    `${student.name} (${student.userId}) · ${student.department} · Generated ${generatedDate}`,
    16,
    23
  );

  let y = 44;
  doc.setTextColor(15, 23, 42);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.text(`Total Enrolled Courses: ${enrollments.length}`, 16, y);
  y += 8;

  enrollments.forEach((item, idx) => {
    if (y > 250) {
      doc.addPage();
      y = 20;
    }
    doc.setDrawColor(226, 232, 240);
    doc.setFillColor(248, 250, 252);
    doc.roundedRect(16, y, 178, 26, 2, 2, 'FD');

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(10.5);
    doc.setTextColor(37, 99, 235);
    doc.text(`${idx + 1}. ${item.courseCode} — ${item.courseTitle}`, 20, y + 8);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9.5);
    doc.setTextColor(51, 65, 85);
    doc.text(
      `Faculty: ${item.facultyName}  |  Semester: ${item.semester}  |  Schedule: ${item.schedule || 'TBA'}`,
      20,
      y + 15
    );
    doc.text(
      `Enrollment ID: ${item.enrollmentId}  |  Enrolled: ${new Date(item.enrolledAt).toLocaleDateString('en-US')}`,
      20,
      y + 21.5
    );
    y += 31;
  });

  doc.save(`CourseHub_Schedule_${student.userId}.pdf`);
}

/**
 * Generates and downloads a generic tabular PDF report for Admin or Faculty
 */
export function downloadTabularReportPdf(options: {
  title: string;
  subtitle: string;
  headers: string[];
  rows: string[][];
  filename: string;
}): void {
  const doc = new jsPDF({ orientation: 'landscape', unit: 'mm', format: 'a4' });
  const generatedDate = new Date().toLocaleString('en-US', {
    dateStyle: 'medium',
    timeStyle: 'short',
  });

  doc.setFillColor(30, 41, 59);
  doc.rect(0, 0, 297, 28, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(15);
  doc.text(`CourseHub Report — ${options.title}`, 14, 13);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9.5);
  doc.text(`${options.subtitle}  |  Generated: ${generatedDate}`, 14, 21);

  const startX = 14;
  const usableWidth = 269;
  const colWidth = usableWidth / Math.max(1, options.headers.length);
  let y = 36;

  const drawHeader = () => {
    doc.setFillColor(241, 245, 249);
    doc.rect(startX, y, usableWidth, 9, 'F');
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(8.5);
    doc.setTextColor(30, 41, 59);
    options.headers.forEach((h, i) => {
      doc.text(String(h).slice(0, 28), startX + i * colWidth + 2, y + 6);
    });
    y += 9;
  };

  drawHeader();

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  options.rows.forEach((row, rowIndex) => {
    if (y > 185) {
      doc.addPage();
      y = 18;
      drawHeader();
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(8);
    }
    if (rowIndex % 2 === 1) {
      doc.setFillColor(248, 250, 252);
      doc.rect(startX, y, usableWidth, 8, 'F');
    }
    doc.setTextColor(15, 23, 42);
    row.forEach((cell, i) => {
      const text = String(cell ?? '').replace(/\s+/g, ' ').slice(0, 32);
      doc.text(text, startX + i * colWidth + 2, y + 5.5);
    });
    y += 8;
  });

  doc.save(options.filename.endsWith('.pdf') ? options.filename : `${options.filename}.pdf`);
}

/**
 * Generates and downloads a RFC-4180 compliant CSV file
 */
export function downloadCsvFile(
  filename: string,
  headers: string[],
  rows: Array<Array<string | number | boolean | null | undefined>>
): void {
  const escapeCsvCell = (val: unknown): string => {
    const str = val === null || val === undefined ? '' : String(val);
    if (/[",\n\r]/.test(str)) {
      return `"${str.replace(/"/g, '""')}"`;
    }
    return str;
  };

  const lines = [
    headers.map(escapeCsvCell).join(','),
    ...rows.map((row) => row.map(escapeCsvCell).join(',')),
  ];

  const csvContent = '\uFEFF' + lines.join('\r\n');
  const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename.endsWith('.csv') ? filename : `${filename}.csv`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
